// Package webfront holds what every host of the SPA must agree on: the
// runtime config.json and the security headers with the content security
// policy (NFA-SEC-05, ADR 0036). The voter, the `pulsequorum frontend`
// subcommand, the header file for CDN hosts and the nginx image all use this
// one implementation. It is security code.
package webfront

import (
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"slices"
	"strings"

	"github.com/joinsider/pulsequorum/internal/cluster"
)

// Content security policies (NFA-SEC-05). The SPA needs inline styles
// (Angular component styles, ECharts); scripts only come from this origin and
// eval is never allowed. API responses are data and get the strictest policy.
const (
	CSPSPA = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; " +
		"img-src 'self' data:; font-src 'self'; connect-src 'self'; object-src 'none'; " +
		"base-uri 'self'; form-action 'self'; frame-ancestors 'none'"
	CSPAPI = "default-src 'none'; frame-ancestors 'none'"
)

// HSTS is the Strict-Transport-Security value for hosts that serve the SPA
// over TLS themselves.
const HSTS = "max-age=31536000"

// Header is one response header.
type Header struct{ Name, Value string }

// commonHeaders are set on every response, SPA and API alike.
var commonHeaders = []Header{
	{"X-Content-Type-Options", "nosniff"},
	{"Referrer-Policy", "no-referrer"},
	{"X-Frame-Options", "DENY"},
	{"Cross-Origin-Opener-Policy", "same-origin"},
}

// SPACSP returns the SPA policy. connect-src allows this origin, the given
// node origins with their WebSocket counterparts (ADR 0036) and, with OIDC,
// the issuer's origin for the token endpoint (ADR 0027). Every node origin is
// checked again with cluster.NormalizePublicOrigin and must already be in
// normalized form, so that no value can inject a directive; nothing else is
// widened.
func SPACSP(issuer string, nodes []string) string {
	sources := make([]string, 0, 2*len(nodes)+1)
	add := func(src string) {
		if !slices.Contains(sources, src) {
			sources = append(sources, src)
		}
	}
	for _, n := range nodes {
		o, err := cluster.NormalizePublicOrigin(n)
		if err != nil || o != n {
			continue
		}
		add(o)
		if rest, ok := strings.CutPrefix(o, "https://"); ok {
			add("wss://" + rest)
		} else if rest, ok := strings.CutPrefix(o, "http://"); ok {
			add("ws://" + rest)
		}
	}
	if o, ok := IssuerOrigin(issuer); ok {
		add(o)
	}
	if len(sources) == 0 {
		return CSPSPA
	}
	return strings.Replace(CSPSPA, "connect-src 'self';", "connect-src 'self' "+strings.Join(sources, " ")+";", 1)
}

// IssuerOrigin returns the origin of the OIDC issuer if it is safe to put
// into a CSP source list.
func IssuerOrigin(issuer string) (string, bool) {
	if issuer == "" {
		return "", false
	}
	u, err := url.Parse(issuer)
	if err != nil || (u.Scheme != "https" && u.Scheme != "http") || u.Host == "" ||
		strings.ContainsAny(u.Host, " ;,'\"\\$\r\n\t") {
		return "", false
	}
	return u.Scheme + "://" + u.Host, true
}

// SPAHeaders returns the headers of an SPA response with policy csp, plus
// HSTS if hsts is set.
func SPAHeaders(csp string, hsts bool) []Header {
	out := slices.Clone(commonHeaders)
	out = append(out, Header{"Content-Security-Policy", csp})
	if hsts {
		out = append(out, Header{"Strict-Transport-Security", HSTS})
	}
	return out
}

// SetCommon sets the headers every response carries.
func SetCommon(h http.Header) {
	for _, x := range commonHeaders {
		h.Set(x.Name, x.Value)
	}
}

// errUnsafeValue means a header value could break out of the file format.
var errUnsafeValue = errors.New("unsafe header value")

// safeValue rejects characters that could end a quoted value or a line, or
// that nginx would expand as a variable.
func safeValue(v string) error {
	for i := 0; i < len(v); i++ {
		if c := v[i]; c < ' ' || c >= 0x7f || c == '"' || c == '\\' || c == '$' {
			return fmt.Errorf("%w: %q", errUnsafeValue, v)
		}
	}
	return nil
}

// NginxConf renders headers as nginx add_header directives for an include
// file in a location block. "always" keeps them on error responses.
func NginxConf(headers []Header) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by pulsequorum-webconfig; do not edit.\n")
	for _, h := range headers {
		if err := safeValue(h.Name); err != nil {
			return "", err
		}
		if err := safeValue(h.Value); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "add_header %s \"%s\" always;\n", h.Name, h.Value)
	}
	return b.String(), nil
}

// HeadersFile renders headers in the `_headers` format of static hosts such
// as Netlify and Cloudflare Pages, for all paths.
func HeadersFile(headers []Header) (string, error) {
	var b strings.Builder
	b.WriteString("/*\n")
	for _, h := range headers {
		if err := safeValue(h.Name); err != nil {
			return "", err
		}
		if err := safeValue(h.Value); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "  %s: %s\n", h.Name, h.Value)
	}
	b.WriteString("/index.html\n  Cache-Control: no-store\n/config.json\n  Cache-Control: no-store\n")
	return b.String(), nil
}

// Command stubgen writes unimplemented.go: one 501 stub per operation of
// gen.StrictServerInterface, so new OpenAPI operations compile immediately.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: stubgen <api.gen.go> <output.go>")
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, os.Args[1], nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	var methods []*ast.Field
	ast.Inspect(file, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "StrictServerInterface" {
			return true
		}
		methods = ts.Type.(*ast.InterfaceType).Methods.List
		return false
	})
	if len(methods) == 0 {
		log.Fatal("StrictServerInterface not found")
	}

	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (C) 2026 The UptimeCluster Authors

// Code generated by internal/api/internal/stubgen; DO NOT EDIT.

package api

import (
	"context"

	"github.com/joinsider/uptimecluster/internal/api/gen"
)

// Unimplemented answers every operation with 501 Not Implemented. Handlers
// embeds it, so an operation goes live once Handlers defines the method.
type Unimplemented struct{}
`)
	for _, m := range methods {
		fn := m.Type.(*ast.FuncType)
		req := fn.Params.List[1].Type.(*ast.Ident).Name
		resp := fn.Results.List[0].Type.(*ast.Ident).Name
		fmt.Fprintf(&b, "\n// %[1]s is not implemented yet.\nfunc (Unimplemented) %[1]s(context.Context, gen.%[2]s) (gen.%[3]s, error) {\n\treturn nil, ErrNotImplemented\n}\n",
			m.Names[0].Name, req, resp)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil { //nolint:gosec // G306: generated Go source must stay readable like other tracked files
		log.Fatal(err)
	}
}
